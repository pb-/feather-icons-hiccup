#!/usr/bin/env bb
(ns script
  (:require [clojure.string :as string]
            [clojure.java.io :as io]
            [clojure.data.xml :as xml]
            [babashka.fs :as fs]))

(defn maybe-numeric [s]
  (or (parse-long s) (parse-double s) s))

(println ";;; EDIT WITH CAUTION - autogenerated with https://github.com/pb-/feather-icons-hiccup")
(println "(ns icons)\n")

(println
  (string/join
    \newline
    ["(defn svg"
     "  ([elements]"
     "   (svg {} elements))"
     "  ([attrs elements]"
     "   (into"
     "     [:svg"
     "      (merge"
     "        {:xmlns \"http://www.w3.org/2000/svg\""
     "         :viewBox \"0 0 24 24\""
     "         :fill \"none\""
     "         :stroke \"currentColor\""
     "         :stroke-width 2"
     "         :stroke-linecap \"round\""
     "         :stroke-linejoin \"round\"}"
     "        attrs)]"
     "     elements)))"])
  \newline)

(doseq [path (sort (fs/list-dir "icons" "*.svg"))
        :let [file (str path)]]
  (with-open [r (io/reader file)]
    (let [parsed (xml/parse r {:namespace-aware false})
          icon (subs file 6 (- (count file) 4))]
      (assert (= :svg (:tag parsed)))
      (println "(def" (if (or (resolve (symbol icon)) (#{"divide"} icon)) (str icon "-icon") icon))
      (print "  [")
      (doseq [[i element] (map-indexed vector (:content parsed))]
        (when (pos? i)
          (print "\n   "))
        (pr [(:tag element) (update-vals (:attrs element) maybe-numeric)]))
      (println "])\n"))))
